use std::{env, fs, path::Path};

fn main() {
    embuild::espidf::sysenv::output();
    generate_model_metadata();
}

/// Turn model/model_metadata.json (written by the notebook's export cell) into
/// Rust constants, so the firmware always uses the class names and input
/// normalisation the model was trained with.
///
/// Required: `class_names` (background first) and `normalization.mean/std`.
/// Optional: `output_activation` ("sigmoid" | "softmax" | "none"),
///           `conf_threshold` (default 0.5).
/// Input size, grid size and channel count are NOT taken from here; the
/// firmware reads them from the .tflite tensors at boot.
fn generate_model_metadata() {
    let path = "model/model_metadata.json";
    println!("cargo:rerun-if-changed={path}");
    println!("cargo:rerun-if-changed=model/fomo_model_int8.tflite");

    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("reading {path}: {e}"));
    let meta: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("parsing {path}: {e}"));

    let class_names: Vec<String> = meta["class_names"]
        .as_array()
        .unwrap_or_else(|| panic!("{path}: missing \"class_names\""))
        .iter()
        .map(|v| v.as_str().expect("class_names must be strings").to_owned())
        .collect();

    let floats = |key: &str| -> Vec<f64> {
        meta["normalization"][key]
            .as_array()
            .unwrap_or_else(|| panic!("{path}: missing \"normalization.{key}\""))
            .iter()
            .map(|v| v.as_f64().expect("normalization values must be numbers"))
            .collect()
    };
    let (mean, std) = (floats("mean"), floats("std"));
    assert_eq!(mean.len(), std.len(), "{path}: mean and std lengths differ");

    let activation = match meta["output_activation"].as_str() {
        Some(a @ ("sigmoid" | "softmax" | "none")) => format!("Some({a:?})"),
        Some(other) => panic!("{path}: unknown output_activation {other:?}"),
        None => "None".to_owned(),
    };
    let threshold = meta["conf_threshold"].as_f64().unwrap_or(0.5);

    let list = |v: &[f64]| {
        v.iter()
            .map(|x| format!("{x:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let code = format!(
        "// Generated by build.rs from {path}. Do not edit.\n\
         pub const CLASS_NAMES: &[&str] = &{class_names:?};\n\
         pub const NORM_MEAN: &[f32] = &[{}];\n\
         pub const NORM_STD: &[f32] = &[{}];\n\
         pub const OUTPUT_ACTIVATION: Option<&str> = {activation};\n\
         pub const CONF_THRESHOLD: f32 = {threshold:?};\n",
        list(&mean),
        list(&std),
    );

    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("model_meta.rs");
    fs::write(out, code).unwrap();
}
