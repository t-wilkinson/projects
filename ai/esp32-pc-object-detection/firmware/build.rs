use std::{env, fmt::Write as _, fs, path::Path};

use serde_json::Value;

const MODEL: &str = "model/fomo_model_int8.tflite";
const METADATA: &str = "model/model_metadata.json";

fn main() {
    embuild::espidf::sysenv::output();
    generate_model_constants();
}

/// Turn model/model_metadata.json (written by the notebook's export cell) into
/// Rust constants: input and grid size, quantisation, class names,
/// normalisation, threshold and the camera frame size that covers the input.
///
/// The .tflite is parsed too, and the build fails if the JSON describes a
/// different model than the file next to it. That catches a model copied in
/// without re-running the export cell, or an export from a stale ONNX file.
fn generate_model_constants() {
    println!("cargo:rerun-if-changed={METADATA}");
    println!("cargo:rerun-if-changed={MODEL}");

    let text = fs::read_to_string(METADATA).unwrap_or_else(|e| fail(&format!("reading it: {e}")));
    let meta: Value =
        serde_json::from_str(&text).unwrap_or_else(|e| fail(&format!("parsing it: {e}")));
    let model_bytes = fs::read(MODEL).unwrap_or_else(|e| panic!("reading {MODEL}: {e}"));
    let model = tflite::read_io(&model_bytes).unwrap_or_else(|e| panic!("{MODEL}: {e}"));

    let m = Meta::parse(&meta).unwrap_or_else(|e| fail(&e));
    let problems = m.check(&model, model_bytes.len());
    if !problems.is_empty() {
        fail(&format!(
            "it doesn't match {MODEL}:\n  - {}\n\
             Re-run the notebook's export cell so both files come from the same model.",
            problems.join("\n  - ")
        ));
    }

    let (camera_w, camera_h, camera_name) = pick_camera_frame(m.input.w, m.input.h);

    let floats = |v: &[f64]| {
        v.iter()
            .map(|x| format!("{x:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut code = format!("// Generated by build.rs from {METADATA}. Do not edit.\n");
    let mut c = |name: &str, ty: &str, value: String| {
        writeln!(code, "pub const {name}: {ty} = {value};").unwrap();
    };
    c("INPUT_W", "usize", m.input.w.to_string());
    c("INPUT_H", "usize", m.input.h.to_string());
    c("INPUT_C", "usize", m.input.c.to_string());
    c("INPUT_SCALE", "f32", format!("{:?}", m.input.scale as f32));
    c("INPUT_ZERO_POINT", "i32", m.input.zero_point.to_string());
    c("GRID_W", "usize", m.output.w.to_string());
    c("GRID_H", "usize", m.output.h.to_string());
    c("OUTPUT_C", "usize", m.output.c.to_string());
    c(
        "OUTPUT_SCALE",
        "f32",
        format!("{:?}", m.output.scale as f32),
    );
    c("OUTPUT_ZERO_POINT", "i32", m.output.zero_point.to_string());
    c("GRID_STRIDE", "usize", m.grid_stride.to_string());
    c("CLASS_NAMES", "&[&str]", format!("&{:?}", m.class_names));
    c("OUTPUT_ACTIVATION", "&str", format!("{:?}", m.activation));
    c("NORM_MEAN", "&[f32]", format!("&[{}]", floats(&m.mean)));
    c("NORM_STD", "&[f32]", format!("&[{}]", floats(&m.std)));
    c(
        "CONF_THRESHOLD",
        "f32",
        format!("{:?}", m.conf_threshold as f32),
    );
    c("CAMERA_W", "usize", camera_w.to_string());
    c("CAMERA_H", "usize", camera_h.to_string());
    c("CAMERA_FRAME", "&str", format!("{camera_name:?}"));
    // The whole file, training hyperparameters included, for GET /api/model.
    let abs = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join(METADATA);
    c(
        "METADATA_JSON",
        "&str",
        format!("include_str!({:?})", abs.display().to_string()),
    );

    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("model_meta.rs");
    fs::write(out, code).unwrap();
}

fn fail(why: &str) -> ! {
    panic!("\n\n{METADATA}: {why}\n\n")
}

/// Shape and quantisation of one NHWC int8 tensor.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Tensor {
    w: usize,
    h: usize,
    c: usize,
    scale: f64,
    zero_point: i64,
}

struct Meta {
    model_size_bytes: usize,
    input: Tensor,
    output: Tensor,
    grid_stride: usize,
    class_names: Vec<String>,
    activation: String,
    mean: Vec<f64>,
    std: Vec<f64>,
    conf_threshold: f64,
}

impl Meta {
    fn parse(j: &Value) -> Result<Self, String> {
        if j.get("format_version").and_then(Value::as_u64) != Some(2) {
            return Err(
                "missing \"format_version\": 2. It was written by an older export \
                        cell; re-run the notebook's export cell."
                    .into(),
            );
        }
        let num = |v: &Value, key: &str| -> Result<f64, String> {
            v.get(key)
                .and_then(Value::as_f64)
                .ok_or_else(|| format!("missing number \"{key}\""))
        };
        let int = |v: &Value, key: &str| -> Result<i64, String> {
            v.get(key)
                .and_then(Value::as_i64)
                .ok_or_else(|| format!("missing integer \"{key}\""))
        };
        let size = |v: &Value, key: &str| -> Result<usize, String> {
            int(v, key)
                .and_then(|n| usize::try_from(n).map_err(|_| format!("\"{key}\" is negative")))
        };
        let tensor = |key: &str| -> Result<Tensor, String> {
            let t = j.get(key).ok_or_else(|| format!("missing \"{key}\""))?;
            let ctx = |e: String| format!("{key}: {e}");
            if t.get("dtype").and_then(Value::as_str) != Some("int8")
                || t.get("layout").and_then(Value::as_str) != Some("NHWC")
            {
                return Err(ctx(
                    "the firmware needs \"dtype\": \"int8\" and \"layout\": \"NHWC\"".into(),
                ));
            }
            Ok(Tensor {
                w: size(t, "width").map_err(ctx)?,
                h: size(t, "height").map_err(ctx)?,
                c: size(t, "channels").map_err(ctx)?,
                scale: num(t, "scale").map_err(ctx)?,
                zero_point: int(t, "zero_point").map_err(ctx)?,
            })
        };
        let floats = |key: &str| -> Result<Vec<f64>, String> {
            j["normalization"][key]
                .as_array()
                .ok_or_else(|| format!("missing \"normalization.{key}\""))?
                .iter()
                .map(|v| {
                    v.as_f64()
                        .ok_or_else(|| format!("normalization.{key} must be numbers"))
                })
                .collect()
        };
        let class_names = j
            .get("class_names")
            .and_then(Value::as_array)
            .ok_or("missing \"class_names\"")?
            .iter()
            .map(|v| {
                v.as_str()
                    .map(str::to_owned)
                    .ok_or("class_names must be strings")
            })
            .collect::<Result<Vec<_>, _>>()?;
        let activation = j
            .get("output_activation")
            .and_then(Value::as_str)
            .ok_or("missing \"output_activation\"")?
            .to_owned();

        Ok(Self {
            model_size_bytes: size(j, "model_size_bytes")?,
            input: tensor("input")?,
            output: tensor("output")?,
            grid_stride: size(j, "grid_stride")?,
            class_names,
            activation,
            mean: floats("mean")?,
            std: floats("std")?,
            conf_threshold: num(j, "conf_threshold")?,
        })
    }

    /// Everything that disagrees with the model or that the firmware can't run.
    fn check(&self, model: &tflite::Io, model_len: usize) -> Vec<String> {
        let mut p = Vec::new();
        if self.model_size_bytes != model_len {
            p.push(format!(
                "model_size_bytes is {} but the .tflite is {model_len} bytes",
                self.model_size_bytes
            ));
        }
        for (name, json, file) in [
            ("input", self.input, model.input),
            ("output", self.output, model.output),
        ] {
            if (json.w, json.h, json.c) != (file.w, file.h, file.c) {
                p.push(format!(
                    "{name} is {}x{}x{} (WxHxC) but the model's is {}x{}x{}",
                    json.w, json.h, json.c, file.w, file.h, file.c
                ));
            }
            if (json.scale - file.scale).abs() > 1e-6 * file.scale.abs().max(1e-9)
                || json.zero_point != file.zero_point
            {
                p.push(format!(
                    "{name} quantisation is scale {} zero point {} but the model's is {} / {}",
                    json.scale, json.zero_point, file.scale, file.zero_point
                ));
            }
        }

        let (i, o) = (self.input, self.output);
        if i.c != 1 && i.c != 3 {
            p.push(format!(
                "input has {} channels; the camera code handles 1 (gray) or 3 (RGB)",
                i.c
            ));
        }
        if self.mean.len() != i.c || self.std.len() != i.c {
            p.push(format!(
                "normalization has {} mean / {} std values for a {}-channel input",
                self.mean.len(),
                self.std.len(),
                i.c
            ));
        }
        if self.std.iter().any(|&s| s <= 0.0) {
            p.push("normalization.std values must be positive".into());
        }
        if o.w == 0 || o.h == 0 || i.w != o.w * self.grid_stride || i.h != o.h * self.grid_stride {
            p.push(format!(
                "grid_stride {} doesn't map the {}x{} input onto the {}x{} grid",
                self.grid_stride, i.w, i.h, o.w, o.h
            ));
        }

        // Same rule as detect.rs: background first, and either a background
        // channel or one channel per foreground class.
        let has_bg = self.class_names.first().map(String::as_str) == Some("background");
        let fg = self.class_names.len() - usize::from(has_bg);
        if fg == 0 || (o.c != fg && o.c != fg + 1) {
            p.push(format!(
                "class_names has {fg} foreground classes but the model outputs {} channels",
                o.c
            ));
        }
        if !matches!(self.activation.as_str(), "sigmoid" | "softmax" | "none") {
            p.push(format!(
                "output_activation {:?} isn't \"sigmoid\", \"softmax\" or \"none\"",
                self.activation
            ));
        }
        if !(self.conf_threshold > 0.0 && self.conf_threshold <= 1.0) {
            p.push(format!(
                "conf_threshold {} isn't in (0, 1]",
                self.conf_threshold
            ));
        }
        p
    }
}

/// Smallest esp32-camera frame size that covers the model input in both
/// directions, so the centre crop resamples as little as possible. The C++
/// side looks the size up in the driver's own resolution table.
fn pick_camera_frame(w: usize, h: usize) -> (usize, usize, &'static str) {
    // Ordered by area. Bigger frames cost PSRAM bandwidth for pixels the crop
    // throws away; the OV2640 and OV3660 support all of these.
    const SIZES: &[(usize, usize, &str)] = &[
        (96, 96, "FRAMESIZE_96X96"),
        (128, 128, "FRAMESIZE_128X128"),
        (160, 120, "FRAMESIZE_QQVGA"),
        (176, 144, "FRAMESIZE_QCIF"),
        (240, 176, "FRAMESIZE_HQVGA"),
        (240, 240, "FRAMESIZE_240X240"),
        (320, 240, "FRAMESIZE_QVGA"),
        (640, 480, "FRAMESIZE_VGA"),
    ];
    *SIZES
        .iter()
        .find(|(fw, fh, _)| *fw >= w && *fh >= h)
        .unwrap_or_else(|| panic!("no camera frame size up to VGA covers a {w}x{h} model input"))
}

/// Just enough of a FlatBuffers reader to get the input and output tensors
/// out of a .tflite file (schema: tensorflow/lite/schema/schema.fbs).
mod tflite {
    use super::Tensor;

    pub struct Io {
        pub input: Tensor,
        pub output: Tensor,
    }

    const INT8: u8 = 9; // TensorType.INT8

    struct Buf<'a>(&'a [u8]);

    impl Buf<'_> {
        fn bytes<const N: usize>(&self, at: usize) -> Result<[u8; N], String> {
            self.0
                .get(at..at + N)
                .and_then(|s| s.try_into().ok())
                .ok_or_else(|| format!("truncated at byte {at}"))
        }
        fn u16(&self, at: usize) -> Result<u16, String> {
            Ok(u16::from_le_bytes(self.bytes(at)?))
        }
        fn u32(&self, at: usize) -> Result<usize, String> {
            Ok(u32::from_le_bytes(self.bytes(at)?) as usize)
        }
        fn i32(&self, at: usize) -> Result<i32, String> {
            Ok(i32::from_le_bytes(self.bytes(at)?))
        }
        /// Follow a uoffset stored at `at`.
        fn deref(&self, at: usize) -> Result<usize, String> {
            Ok(at + self.u32(at)?)
        }
        /// Position of field `n` of the table at `table`, if present.
        fn field(&self, table: usize, n: usize) -> Result<Option<usize>, String> {
            let vtable = (table as i64 - self.i32(table)? as i64) as usize;
            let slot = 4 + 2 * n;
            if slot >= self.u16(vtable)? as usize {
                return Ok(None);
            }
            let off = self.u16(vtable + slot)? as usize;
            Ok((off != 0).then_some(table + off))
        }
        fn required(&self, table: usize, n: usize, what: &str) -> Result<usize, String> {
            self.field(table, n)?
                .ok_or_else(|| format!("missing {what}"))
        }
        /// (first element, length) of the vector referenced at `at`.
        fn vector(&self, at: usize) -> Result<(usize, usize), String> {
            let v = self.deref(at)?;
            Ok((v + 4, self.u32(v)?))
        }
        fn table_at(&self, vec_at: usize, i: usize) -> Result<usize, String> {
            let (start, len) = self.vector(vec_at)?;
            if i >= len {
                return Err(format!("index {i} out of range ({len})"));
            }
            self.deref(start + 4 * i)
        }
        fn i32s(&self, vec_at: usize) -> Result<Vec<i32>, String> {
            let (start, len) = self.vector(vec_at)?;
            (0..len).map(|k| self.i32(start + 4 * k)).collect()
        }
    }

    pub fn read_io(data: &[u8]) -> Result<Io, String> {
        let b = Buf(data);
        let model = b.deref(0)?;
        // Model: 0 version, 2 subgraphs
        let subgraph = b.table_at(b.required(model, 2, "subgraphs")?, 0)?;
        // SubGraph: 0 tensors, 1 inputs, 2 outputs
        let tensors = b.required(subgraph, 0, "tensors")?;
        let one = |field: usize, what: &str| -> Result<Tensor, String> {
            let ids = b.i32s(b.required(subgraph, field, what)?)?;
            let [id] = ids[..] else {
                return Err(format!("expected one {what} tensor, found {}", ids.len()));
            };
            tensor(&b, b.table_at(tensors, id as usize)?).map_err(|e| format!("{what} tensor: {e}"))
        };
        Ok(Io {
            input: one(1, "input")?,
            output: one(2, "output")?,
        })
    }

    fn tensor(b: &Buf, t: usize) -> Result<Tensor, String> {
        // Tensor: 0 shape, 1 type, 4 quantization
        let shape = b.i32s(b.required(t, 0, "shape")?)?;
        let ty = match b.field(t, 1)? {
            Some(at) => b.bytes::<1>(at)?[0],
            None => 0, // FLOAT32 is the default
        };
        if ty != INT8 {
            return Err(format!(
                "type {ty} is not int8 (9); export with inference_input_type/output_type = tf.int8"
            ));
        }
        let [1, h, w, c] = shape[..] else {
            return Err(format!("shape {shape:?} is not [1, H, W, C]"));
        };
        // QuantizationParameters: 2 scale [float], 3 zero_point [long]
        let q = b.deref(b.required(t, 4, "quantization")?)?;
        let (scales, n) = b.vector(b.required(q, 2, "quantization scale")?)?;
        let (zps, m) = b.vector(b.required(q, 3, "quantization zero point")?)?;
        if n != 1 || m != 1 {
            return Err(format!(
                "expected per-tensor quantisation, found {n} scales"
            ));
        }
        Ok(Tensor {
            w: w as usize,
            h: h as usize,
            c: c as usize,
            scale: f32::from_le_bytes(b.bytes(scales)?) as f64,
            zero_point: i64::from_le_bytes(b.bytes(zps)?),
        })
    }
}
